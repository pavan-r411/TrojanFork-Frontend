import assert from 'node:assert/strict';
import { recalculatePlan, preserveLocked, selectInPlan, previewSwap } from '../live-plan.js';
import { daily, log, remove, setTargets, updatePlan } from '../nutrition-local.js';
import { directionsUrl, directionsUnavailable } from '../api.js';
const item={id:'food',meal_title:'Live bowl',price_cents:1100,nutrition:{calories:null,protein_g:30,carbs_g:null,fat_g:null,status:'published',serving_size:'1 bowl'}};
const plan={plan_id:'p',mode:'off_campus',date:'2026-11-14',summary:{},slots:[{slot:'lunch',locked:false,selected_recommendation_id:null,recommendations:[item]}]};
recalculatePlan(plan,{daily_budget_cents:4200});
assert.equal(plan.summary.total_cost_cents,0);
const chosen=selectInPlan({plan_id:'p',plan_state:plan,slot:'lunch',selected_recommendation_id:'food',locked_meal_ids:[]});
assert.equal(chosen.summary.total_cost_cents,1100);
assert.equal(chosen.summary.nutrition.calories,null);
assert.equal(chosen.summary.remaining_budget_cents,3100);
assert.equal(plan.slots[0].selected_recommendation_id,null);
const fresh=structuredClone(plan);fresh.slots[0].recommendations=[];
preserveLocked(fresh,chosen,['food']);
assert.equal(fresh.slots[0].locked,true);
assert.equal(fresh.slots[0].selected_recommendation_id,'food');
assert.throws(()=>selectInPlan({plan_id:'p',plan_state:fresh,slot:'lunch',selected_recommendation_id:'food',locked_meal_ids:['food']}),/Unlock/);
updatePlan(chosen);
assert.equal(daily(plan.date).planned.calories,null);
assert.equal(daily(plan.date).logs.length,0);
setTargets(plan.date,{calories:2200,protein_g:130,carbs_g:null,fat_g:null});
const body={date:plan.date,slot:'lunch',portion:1.5,idempotency_key:'log'};
const logged=log(body,item);
assert.equal(logged.consumed.protein_g,45);
assert.equal(logged.consumed.calories,null);
assert.equal(log(body,item).logs.length,1);
assert.equal(remove(plan.date,'log').consumed.calories,0);
console.log('PASS: live plan selections, locked choices, session logging, portions, targets and unknown totals.');
const estimated={...item,id:'estimated',price_cents:1200,price_status:'estimated',nutrition:{...item.nutrition,calories:550,status:'estimated',published:{calories:null,protein_g:30,carbs_g:null,fat_g:null},estimated_ranges:{calories:{low:450,high:650}}}};
const estimatedLog=log({...body,idempotency_key:'estimated',actual_price_cents:1050},estimated);
assert.equal(estimatedLog.includes_estimates,true);
assert.equal(estimatedLog.logs.at(-1).price_quality,'user_entered');
assert.equal(estimatedLog.logs.at(-1).price_cents,1050);
assert.equal(estimatedLog.logs.at(-1).published_nutrition.calories,null);
assert.equal(estimatedLog.logs.at(-1).nutrition.calories,825);
remove(plan.date,'estimated');
const alt={...item,id:'alt',meal_title:'Other bowl',price_cents:900,venue:{name:'Cafe B'},nutrition:{calories:400,protein_g:20,carbs_g:null,fat_g:null,status:'published'}};
const two={plan_id:'p2',mode:'off_campus',date:'2026-11-14',summary:{},client_context:{daily_budget_cents:4200,meal_swipes_available:3},slots:[{slot:'lunch',locked:false,selected_recommendation_id:'food',recommendations:[{...item,venue:{name:'Cafe A'}},alt]}]};
recalculatePlan(two,two.client_context);
const preview=previewSwap(two,'lunch','alt');
assert.equal(preview.delta.cash_cents,-200);
assert.equal(preview.delta.restaurant_changed,true);
assert.equal(preview.to.title,'Other bowl');
assert.equal(directionsUrl({directions:{available:true,url:'https://www.google.com/maps/dir/?api=1&destination=1,2&travelmode=walking'}})?.includes('google.com/maps'),true);
assert.equal(directionsUrl({directions:{available:false,url:null}}),null);
assert.match(directionsUnavailable({directions:{available:false,unavailable_reason:'missing_destination'}}),/missing_destination|unavailable/i);
assert.match(directionsUrl({raw:{venue:{lat:34.02,lng:-118.28,name:'CAVA'}}}),/destination=34\.02/);
assert.equal(directionsUrl({directions:{available:false,unavailable_reason:'stale_truck_location',url:null},raw:{venue:{lat:34.02,lng:-118.28}}}),null);
console.log('PASS: swap preview deltas and directions availability helpers.');
